import assert from 'node:assert/strict';
import vm from 'node:vm';
import fs from 'node:fs';
import ts from 'typescript';
const events=[];
const context={exports:{},window:{gtag:(...args)=>events.push(args)}};
const compiled=ts.transpileModule(fs.readFileSync('lib/contact.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
vm.runInNewContext(compiled,context);
const {trackContact,contactMessage}=context.exports;
trackContact('whatsapp','enquiry');trackContact('phone');
assert.deepEqual(JSON.parse(JSON.stringify(events)),[['event','generate_lead',{method:'whatsapp',placement:'enquiry'}],['event','contact_click',{method:'phone',placement:'site'}]]);
const secret='Private draft for test only';
const draft=contactMessage('project','Starting from scratch','Websites & Digital Growth Infrastructure',` ${secret} `);
assert(draft.includes('a project') && draft.includes('Starting from scratch') && draft.endsWith(secret));
assert(!JSON.stringify(events).includes(secret),'Enquiry content must not enter analytics');
assert(!JSON.stringify(events).includes('link_url'),'Contact events must not include message-bearing URLs');
assert(contactMessage('unknown','Not sure yet',undefined,'').includes('a technology consultation'));
assert(!contactMessage('support','Not sure yet',undefined,'').includes('undefined'));
context.window.gtag=undefined;trackContact('whatsapp');
console.log('PASS: WhatsApp and phone event names/payloads, enquiry context, no draft or URL in custom analytics, and graceful behaviour when analytics is unavailable.');